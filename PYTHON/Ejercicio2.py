"""
Ejercicio 2 — Calculadora básica

Pide al usuario dos números y muestra:

La suma
La resta
La multiplicación
La división
"""
print("Digite el primer número: ")
num1 = float(input())
print("Digite el segundo número: ")
num2 = float(input())
print("Suma: "+ str(num1+num2))
print("Resta: "+ str(num1-num2))
print("Multiplicacion: "+ str(num1*num2))
print("Division: "+ str(num1/num2))